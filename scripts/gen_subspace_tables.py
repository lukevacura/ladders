"""Writes the constant tables of the `subspace` and `mdl` modules, each entry correctly rounded.

`crates/core/src/subspace/edges.rs`: STUMPY's 255 bin edges, the standard normal quantiles
`sqrt(2) * erfinv(2 i / 256 - 1)` for `i` in `1..=255`. The edges for fewer bits are every
`2^(8 - bits)`-th of these.

`crates/core/src/mdl/log2.rs`: `log2(n)` for `n` in `1..=512`.

Each entry is computed with mpmath at two precisions. The entry is the nearest f64 to the value,
and the rounding is decided: both precisions give the same f64, and the value is farther than a
margin far above the computation's error from the midpoints to that f64's neighbours, where the
rounding would turn. No floating-point library decides an entry, so every platform computes the
same tables.

`python scripts/gen_subspace_tables.py` rewrites the files; `--check` exits non-zero when a file
differs from what is computed here, and writes nothing.
"""

import math
import sys
from fractions import Fraction
from pathlib import Path

import mpmath

CORE = Path(__file__).resolve().parent.parent / "crates" / "core" / "src"
LOG2_COUNT = 512
EDGE_COUNT = 255
PRECISIONS = (200, 260)
# The value must be farther than this, relative, from a rounding boundary: 2^-150 at 200 bits.
MARGIN_BITS = 150


def exact(value: mpmath.mpf) -> Fraction:
    mantissa, exponent = mpmath.mpf(value).man_exp
    return Fraction(int(mantissa)) * Fraction(2) ** int(exponent)


def decided(value: Fraction) -> float:
    """The nearest f64 to `value`, after checking that `value` is not within the margin of the
    midpoint between that f64 and either neighbour."""
    nearest = float(value)  # int / int true division is correctly rounded.
    if value == 0:
        return nearest
    margin = abs(value) / Fraction(2) ** MARGIN_BITS
    for neighbour in (math.nextafter(nearest, math.inf), math.nextafter(nearest, -math.inf)):
        boundary = (Fraction(nearest) + Fraction(neighbour)) / 2
        assert abs(value - boundary) > margin, f"{float(value)!r} is within the margin of a rounding boundary"
    return nearest


def correctly_rounded(compute) -> float:
    """`compute()` evaluated with mpmath at every working precision, rounded to f64 once."""
    results = []
    for precision in PRECISIONS:
        with mpmath.workprec(precision):
            results.append(decided(compute()))
    assert all(r == results[0] for r in results), results
    return results[0]


def normal_quantile(i: int, n: int) -> float:
    """`sqrt(2) * erfinv(2 i / n - 1)`; `2 i / n - 1` is exact in mpmath's binary arithmetic."""
    return correctly_rounded(lambda: mpmath.sqrt(2) * mpmath.erfinv(mpmath.mpf(2 * i - n) / n))


def edges() -> list[float]:
    values = [normal_quantile(i, 256) for i in range(1, EDGE_COUNT + 1)]
    assert values[127] == 0.0 and not math.copysign(1.0, values[127]) < 0
    assert all(a == -b for a, b in zip(values, reversed(values)))
    assert all(a < b for a, b in zip(values, values[1:]))
    for bits in range(1, 9):
        wanted = [normal_quantile(i, 2**bits) for i in range(1, 2**bits)]
        assert wanted == [values[(i << (8 - bits)) - 1] for i in range(1, 2**bits)], bits
    return values


def edges_source() -> str:
    lines = "".join(f"    {value!r},\n" for value in edges())
    return (
        "//! Generated by scripts/gen_subspace_tables.py; do not edit.\n\n"
        "/// STUMPY's bin edges for eight bits, the normal quantiles `sqrt(2) * erfinv(2 i / 256 - 1)`\n"
        "/// for `i` in `1..=255`, each correctly rounded.\n"
        f"pub(super) const EDGES: [f64; {EDGE_COUNT}] = [\n{lines}];\n"
    )


def correctly_rounded_log2(n: int) -> float:
    if n & (n - 1) == 0:
        return float(n.bit_length() - 1)
    return correctly_rounded(lambda: mpmath.log(n, 2))


def log2_source() -> str:
    values = [correctly_rounded_log2(n) for n in range(1, LOG2_COUNT + 1)]
    lines = "".join(f"    {value!r},\n" for value in values)
    return (
        "//! Generated by scripts/gen_subspace_tables.py; do not edit.\n\n"
        "#![allow(clippy::approx_constant)]\n\n"
        "/// `log2(n)` correctly rounded, at index `n - 1`, for `n` in `1..=512`.\n"
        f"pub(super) const LOG2: [f64; {LOG2_COUNT}] = [\n{lines}];\n"
    )


def main() -> int:
    outputs = {
        CORE / "subspace" / "edges.rs": edges_source(),
        CORE / "mdl" / "log2.rs": log2_source(),
    }
    stale = [path for path, text in outputs.items() if not path.exists() or path.read_text() != text]
    if "--check" in sys.argv:
        for path in stale:
            print(f"{path} differs from what is computed", file=sys.stderr)
        return 1 if stale else 0
    for path, text in outputs.items():
        path.parent.mkdir(exist_ok=True)
        path.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
